"""The evidence engine's validation experiments (PRD §10.9, E-E; M5, M6, M8).

    python -m evals.evidence.evaluate            # write metrics.json, report.md, evidence.png
    python -m evals.evidence.evaluate --check    # CI: re-run the reduced gate, compare

Everything runs on the simulator's model with fixed seeds, so the numbers are deterministic:
- ``coverage``: M6, empirical coverage of nominal 95% PPI intervals (``coverage.py``);
- ``detection``: M5, detection delay at a matched false-alarm rate (``detection.py``);
- ``sensitivity``: §10.9 item 3, the gate with and without PPI, and a drifting judge;
- ``cost``: M8, shadow + judge cost as a share of routed spend, measured through the gateway;
- ``canary``: Phase 13, a bad canary is rolled back and a good one is recommended.

**The CI gate.** The full experiments take a minute or two, too slow for every check, so
``--check`` re-runs a *reduced* version of each (fewer runs, same seeds) and compares its
headline numbers, rounded to 4 decimals, with the ``gate`` section of the committed
``metrics.json``. Any change to the statistics, the cards or the shadow stage that moves a
number fails CI until ``make eval-evidence`` is re-run and the new metrics committed
(CLAUDE.md: any change to router, cache or policy re-runs the evals).

Every target is reported whether or not it is met.
"""

import argparse
import json
import sys
from pathlib import Path
from typing import Any

from evals.evidence import canary, cost, coverage, detection, sensitivity

HERE = Path(__file__).parent


def full() -> dict[str, Any]:
    return {
        "coverage": coverage.run(),
        "detection": detection.run(),
        "sensitivity": sensitivity.run(),
        "cost": cost.run(),
        "canary": canary.run(),
    }


def gate() -> dict[str, float]:
    """Small, fast, deterministic versions of each experiment: the numbers CI compares."""
    cov = coverage.run(
        n_humans=(50, 100), n_judges=(500,), ws=(0.9, 0.95), judges=("good",), runs=300, n_boot=200
    )
    det = detection.run(n_streams=200)
    sen = sensitivity.run(runs=400)
    m8 = cost.run(n_requests=200)
    can = canary.run(runs=20)
    out = {
        "coverage_wald_worst": cov["worst"]["wald"],
        "coverage_bootstrap_worst": cov["worst"]["bootstrap"],
        "detection_fixed_median": det["monitors"]["fixed_threshold"]["median_delay"],
        "detection_e1_median": det["monitors"]["e1_matched"]["median_delay"],
        "false_safe_ppi_loss_blind": sen["false_safe"]["loss_blind"]["ppi"],
        "false_safe_judge_only_loss_blind": sen["false_safe"]["loss_blind"]["judge_only"],
        "false_safe_ppi_drifted": sen["false_safe"]["drifted"]["ppi"],
        "m8_share": m8["undecided_rate"]["share"],
        "canary_bad_rolled_back": can["bad"]["rolled_back"],
        "canary_good_rolled_back": can["good"]["rolled_back"],
    }
    return {k: round(float(v), 4) for k, v in out.items()}


def write_text(path: Path, text: str) -> None:
    # LF on every platform: the committed files are compared byte for byte in CI (Linux).
    with open(path, "w", encoding="utf-8", newline="\n") as f:
        f.write(text)


def report(m: dict[str, Any]) -> str:
    cov, det, sen, m8, can = m["coverage"], m["detection"], m["sensitivity"], m["cost"], m["canary"]
    yes = {True: "**met**", False: "**not met**"}
    lines = [
        "# Evidence engine: validation experiments",
        "",
        "Generated by `make eval-evidence` (`python -m evals.evidence.evaluate`). Simulated: "
        "the numbers measure the statistics and the machinery, on the simulator's model of "
        "quality and judge error (PRD §11.1), not real traffic.",
        "",
        "## M6: interval coverage (target >= 93%)",
        "",
        f"{cov['runs_per_cell']} datasets per cell; {len(cov['cells'])} cells (human labels x "
        f"judge-only pairs x true w x judge). Worst cell: Wald {cov['worst']['wald']:.3f}, "
        f"bootstrap {cov['worst']['bootstrap']:.3f}. Cells below target: Wald "
        f"{cov['cells_below_target']['wald']}, bootstrap {cov['cells_below_target']['bootstrap']}."
        f" Interval used by the cards: **{cov['chosen_interval']}**; M6 {yes[cov['met']]}.",
        "",
        "With 1,000 runs a coverage estimate has a Monte Carlo standard error of about 0.008, "
        "so cells within ~0.01 of 0.93 are not clearly below it.",
        "",
        "| n human | n judge | w | judge | Wald | bootstrap | Wald width | bootstrap width |",
        "|---|---|---|---|---|---|---|---|",
    ]
    for c in cov["cells"]:
        flag = " ⚠" if min(c["wald"], c["bootstrap"]) < cov["target"] else ""
        lines.append(
            f"| {c['n_human']} | {c['n_judge']} | {c['w']} | {c['judge']} | {c['wald']:.3f} "
            f"| {c['bootstrap']:.3f}{flag} | {c['wald_width']:.3f} | {c['bootstrap_width']:.3f} |"
        )
    mon = det["monitors"]
    lines += [
        "",
        "## M5: detection delay at a matched false-alarm rate",
        "",
        f"w drops {det['w_before']} -> {det['w_after']} (floor {det['floor']}); "
        f"{det['streams']} null and {det['streams']} change streams; false alarms over "
        f"{det['horizon']} judged samples, target <= {det['false_alarm_target']:.0%}. Delay in "
        "judged samples after the change.",
        "",
        "| monitor | knob | false-alarm rate | median delay | p25-p75 | detected |",
        "|---|---|---|---|---|---|",
    ]
    for name, r in mon.items():
        knob = (
            f"window {r['window']}"
            if "window" in r
            else f"block {r['block']}, z {r['z']}, lambda {r['lambda']}"
            if "z" in r
            else "-"
        )
        spread = f"{r['p25_delay']:.0f}-{r['p75_delay']:.0f}" if "p25_delay" in r else "-"
        lines.append(
            f"| {name} | {knob} | {r['false_alarm_rate']:.3f} | {r['median_delay']:.0f} "
            f"| {spread} | {r['detected_within_horizon']:.1%} |"
        )
    lines += [
        "",
        f"Faster at matched false alarms: **{det['faster_at_matched_false_alarms']}**; "
        f"M5 (E1 faster than the fixed threshold) {yes[det['met']]}.",
        "",
        "Why `lambda = 1` for E1: PPI++ tunes lambda on human labels from *before* the change; "
        "with few losses at w = 0.95 it is about 0.3, so the estimate leans on the stale human "
        "mean (`e1_ppi_pp_*` rows). The pre-registered Bonferroni E1 (`e1_bonferroni`) is valid "
        "by construction but, with 20 looks at alpha/20, slow: that is the price E2 (anytime-"
        "valid sequences, future scope) would remove.",
        "",
        "## Judge sensitivity: the gate with and without PPI",
        "",
        f"{sen['runs']} decisions per row; floor {sen['floor']}; {sen['n_human']} human labels, "
        f"{sen['n_judge']} judge-only pairs. A truly bad candidate (w = 0.86) declared "
        "**safe** is the dangerous error; a truly good one (w = 0.96) declared safe is right.",
        "",
        "| judge | bad declared safe: PPI | judge only | good declared safe: PPI | judge only |",
        "|---|---|---|---|---|",
    ]
    for name in ("good", "mediocre", "loss_blind", "drifted"):
        r = sen[name]
        lines.append(
            f"| {name} | {r['bad']['ppi']['safe']:.3f} | {r['bad']['judge_only']['safe']:.3f} "
            f"| {r['good']['ppi']['safe']:.3f} | {r['good']['judge_only']['safe']:.3f} |"
        )
    lines += [
        "",
        "`drifted`: the judge was calibrated (good) when the human labels were collected, then "
        "became loss-blind. The rectifier is stale, and PPI's protection shrinks: the reason "
        "cards go `stale` and §10.4 asks for fresh labels after any change.",
        "",
        "## M8: evidence cost share (target <= 10%)",
        "",
        "| sample rate | requests | shadow pairs | routed list cost | evidence list cost | share |",
        "|---|---|---|---|---|---|",
    ]
    for key in ("undecided_rate", "decided_rate"):
        r = m8[key]
        lines.append(
            f"| {r['sample_rate']} | {r['requests']} | {r['shadow_pairs']} "
            f"| ${r['routed_list_nano_usd'] / 1e9:.4f} | ${r['evidence_list_nano_usd'] / 1e9:.4f} "
            f"| {r['share']:.2%} |"
        )
    lines += [
        "",
        f"Traffic mix: {m8['cheap_share']:.0%} cheap (the simulated router's share); judge "
        f"{m8['judge']}. M8 {yes[m8['met']]}.",
        "",
        "## Canary (Phase 13): automatic rollback on an unsafe card",
        "",
        f"{can['runs']} simulated canaries each; floor {can['floor']}; looks every "
        f"{can['look_every']} judged pairs, at most {can['max_looks']}.",
        "",
        "| canary | true w | rolled back | promoted (recommended) | still undecided "
        "| median judged pairs to the decision |",
        "|---|---|---|---|---|---|",
    ]
    for name in ("bad", "good"):
        r = can[name]
        lines.append(
            f"| {name} | {r['w']} | {r['rolled_back']:.1%} | {r['promote_recommended']:.1%} "
            f"| {r['undecided']:.1%} | {r['median_pairs_to_decision']} |"
        )
    lines += [
        "",
        "A good canary is only ever *recommended* for promotion; a human runs `promote` "
        "(ADR 0022).",
        "",
    ]
    return "\n".join(lines)


def plot(m: dict[str, Any], path: Path) -> bool:
    try:
        import matplotlib

        matplotlib.use("Agg")
        import matplotlib.pyplot as plt
    except ImportError:
        return False
    fig, (a, b) = plt.subplots(1, 2, figsize=(11, 4.2))
    cells = sorted(m["coverage"]["cells"], key=lambda c: c["wald"])
    xs = range(len(cells))
    a.plot(xs, [c["wald"] for c in cells], "o", ms=3, label="Wald (PPI++)")
    a.plot(xs, [c["bootstrap"] for c in cells], "x", ms=3, label="percentile bootstrap")
    a.axhline(0.95, color="grey", ls=":", lw=1)
    a.axhline(m["coverage"]["target"], color="C3", ls="--", lw=1, label="M6 target")
    a.set_xlabel("grid cell (sorted by Wald coverage)")
    a.set_ylabel("empirical coverage")
    a.set_title("M6: coverage of nominal 95% intervals")
    a.legend(loc="lower right")
    mon = m["detection"]["monitors"]
    names = ["fixed_threshold", "e1_matched", "e1_ppi_pp_matched", "e1_bonferroni"]
    b.barh(names, [mon[n]["median_delay"] for n in names], color=["C0", "C1", "C2", "C4"])
    b.set_xlabel("median detection delay (judged samples)")
    b.set_title("M5: delay at matched false-alarm rate")
    fig.tight_layout()
    fig.savefig(path, dpi=130)
    plt.close(fig)
    return True


def main() -> int:
    parser = argparse.ArgumentParser(prog="python -m evals.evidence.evaluate", description=__doc__)
    parser.add_argument("--check", action="store_true", help="compare with the committed gate")
    args = parser.parse_args()
    path = HERE / "metrics.json"
    if args.check:
        if not path.exists():
            print(f"{path} is missing: run `make eval-evidence` and commit it")
            return 1
        old = json.loads(path.read_text(encoding="utf-8"))["gate"]
        new = gate()
        diff = [f"{k}: {old.get(k)} -> {v}" for k, v in new.items() if old.get(k) != v]
        if diff:
            print("evidence eval changed vs the committed baseline: " + "; ".join(diff))
            print("If intended, run `make eval-evidence` and commit the new metrics.json.")
            return 1
        print(f"evidence eval OK: {new}")
        return 0
    metrics = {**full(), "gate": gate()}
    write_text(path, json.dumps(metrics, indent=2) + "\n")
    write_text(HERE / "report.md", report(metrics))
    plotted = plot(metrics, HERE / "evidence.png")
    print(json.dumps(metrics["gate"], indent=2))
    print("wrote metrics.json, report.md" + (", evidence.png" if plotted else ""))
    return 0


if __name__ == "__main__":
    sys.exit(main())
