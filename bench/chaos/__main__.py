"""``python -m bench.chaos``: run scenarios, aggregate over runs, write the results.

    python -m bench.chaos --runs 5                       # the full suite (make chaos)
    python -m bench.chaos --scenarios hard_outage --smoke --runs 2

Results go to ``bench/results/chaos/``: one JSON per scenario, ``summary.md``, and a chart.
They are committed (docs/ is git-ignored, and PRD §5 says README numbers must come from
``make reproduce``), and every file says it came from the simulator.
"""

import argparse
import asyncio
import json
from pathlib import Path
from typing import Any

from bench.chaos.metrics import mean_and_spread
from bench.chaos.runner import CLIENT_NAMES, SCENARIOS, run_scenario

RESULTS = Path(__file__).resolve().parents[1] / "results" / "chaos"
METRICS = (
    "success_rate",
    "incident_success_rate",
    "p95_s",
    "p99_s",
    "retry_amplification",
    "primary_burstiness",
    "degraded",
    "silent_truncations",
    "wrong_rate_first_half",
    "wrong_rate_second_half",
)


def aggregate(result: dict[str, Any]) -> dict[str, Any]:
    """Collapse each client's runs into mean +/- stdev per metric."""
    out = {k: v for k, v in result.items() if k != "clients"}
    out["clients"] = {}
    for client, runs in result["clients"].items():
        stats = {}
        for metric in METRICS:
            values = [float(r[metric]) for r in runs if metric in r]
            if values:
                mean, sd = mean_and_spread(values)
                stats[metric] = {"mean": mean, "stdev": sd, "runs": values}
        out["clients"][client] = stats
    return out


def fmt(stat: dict[str, Any] | None, pct: bool = False) -> str:
    if not stat:
        return "-"
    m, s = stat["mean"], stat["stdev"]
    return f"{m * 100:.1f}% +/- {s * 100:.1f}" if pct else f"{m:.2f} ± {s:.2f}"


def summary_md(results: list[dict[str, Any]], smoke: bool) -> str:
    lines = [
        "# Chaos results (simulator)",
        "",
        "Generated by `python -m bench.chaos`. **Simulator results, not measurements of real "
        "providers** (PRD §13). Mean +/- stdev over runs (PRD §11.1). "
        + ("**Smoke scale: compressed timelines.**" if smoke else ""),
        "",
        "Success follows PRD M2: a complete 2xx; streams must end with `[DONE]`; Relay's own "
        "429/503 and mid-stream failures count as failures. LiteLLM is not compared yet "
        "(deferred, ADR 0012).",
        "",
    ]
    for r in results:
        lines += [
            f"## {r['scenario']}",
            "",
            r["description"],
            "",
            f"{r['runs']} run(s) of {r['duration_s']:.0f} s at {r['rps']:.0f} req/s.",
            "",
            "| client | success | in incident | p95 s | retry amp. | burstiness | degraded |",
            "|---|---|---|---|---|---|---|",
        ]
        for client, s in r["clients"].items():
            lines.append(
                f"| {client} | {fmt(s.get('success_rate'), True)} | "
                f"{fmt(s.get('incident_success_rate'), True)} | {fmt(s.get('p95_s'))} | "
                f"{fmt(s.get('retry_amplification'))} | {fmt(s.get('primary_burstiness'))} | "
                f"{fmt(s.get('degraded'))} |"
            )
        for client, s in r["clients"].items():
            if "wrong_rate_first_half" in s:
                lines += [
                    "",
                    f"Ground truth ({client}): wrong answers "
                    f"{fmt(s['wrong_rate_first_half'], True)} before the shift, "
                    f"{fmt(s['wrong_rate_second_half'], True)} after. "
                    "Nothing detects this yet (Phase 12).",
                ]
        lines.append("")
    return "\n".join(lines)


def chart(results: list[dict[str, Any]], path: Path) -> bool:
    try:
        import matplotlib

        matplotlib.use("Agg")
        import matplotlib.pyplot as plt
    except ImportError:
        return False
    fig, ax = plt.subplots(figsize=(max(6, 1.6 * len(results)), 4))
    width = 0.8 / len(CLIENT_NAMES)
    for j, client in enumerate(CLIENT_NAMES):
        xs, ys, errs = [], [], []
        for i, r in enumerate(results):
            stat = r["clients"].get(client, {}).get("success_rate")
            if stat:
                xs.append(i + j * width)
                ys.append(stat["mean"] * 100)
                errs.append(stat["stdev"] * 100)
        ax.bar(xs, ys, width, yerr=errs, label=client)
    ax.set_xticks([i + width for i in range(len(results))])
    ax.set_xticklabels([r["scenario"] for r in results], rotation=25, ha="right")
    ax.set_ylabel("request success (%)")
    ax.set_ylim(0, 105)
    ax.set_title("Chaos suite on the simulator (mean +/- stdev over runs)")
    ax.legend()
    fig.tight_layout()
    fig.savefig(path, dpi=130)
    plt.close(fig)
    return True


async def main_async(args: argparse.Namespace) -> None:
    names = (
        args.scenarios.split(",")
        if args.scenarios
        else sorted(p.stem for p in SCENARIOS.glob("*.yaml") if p.stem != "base")
    )
    clients = tuple(args.clients.split(","))
    RESULTS.mkdir(parents=True, exist_ok=True)
    aggregated = []
    for name in names:
        print(f"== {name} ({args.runs} run(s) x {len(clients)} client(s))", flush=True)
        raw = await run_scenario(name, clients, args.runs, smoke=args.smoke)
        agg = aggregate(raw)
        aggregated.append(agg)
        out = RESULTS / f"{name}{'.smoke' if args.smoke else ''}.json"
        out.write_text(json.dumps({**agg, "raw": raw["clients"]}, indent=2), encoding="utf-8")
        for client, s in agg["clients"].items():
            print(f"   {client:12s} success {fmt(s.get('success_rate'), True)}", flush=True)
    suffix = ".smoke" if args.smoke else ""
    (RESULTS / f"summary{suffix}.md").write_text(
        summary_md(aggregated, args.smoke), encoding="utf-8"
    )
    if chart(aggregated, RESULTS / f"success{suffix}.png"):
        print("chart written")


def main() -> None:
    parser = argparse.ArgumentParser(prog="python -m bench.chaos", description=__doc__)
    parser.add_argument("--scenarios", help="comma-separated names (default: all)")
    parser.add_argument("--clients", default=",".join(CLIENT_NAMES))
    parser.add_argument("--runs", type=int, default=5)
    parser.add_argument("--smoke", action="store_true", help="compress timelines")
    asyncio.run(main_async(parser.parse_args()))


if __name__ == "__main__":
    main()
